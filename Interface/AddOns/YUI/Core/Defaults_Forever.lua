local function CopyProfile(source)
    local result = {}
    for key, value in pairs(source) do
        result[key] = type(value) == "table" and CopyProfile(value) or value
    end
    return result
end

function YUI:ApplyForeverFactoryProfile(db, savedVariableName)
    if not self.IsForever or self.CoreMode ~= "suite" or savedVariableName ~= "YUI_DB" or not db then return end
    local profile = db.profile
    -- 不把复杂列表注册为 AceDB 默认值，避免用户删除的按钮／实例在重载时重新出现。
    -- 已有配置整份保留，由各模块继续使用自己的缺省补全规则。
    for key in pairs(profile) do
        if key ~= "WhisperColor" and key ~= "PluginSkins_DetailsSpecSync" then return end
    end
    for key, value in pairs(self.ForeverFactoryProfile) do
        profile[key] = type(value) == "table" and CopyProfile(value) or value
    end
end

