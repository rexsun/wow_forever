local YUI = _G.YUI
if not YUI or not YUI.YActionBar then return end

local YAB = YUI.YActionBar

function YAB:GetStats()
    local db = self.GetDB and self:GetDB() or nil
    local barStats = self.BarManager and self.BarManager:GetStats() or {}
    local keyStats = self.Keybinds and self.Keybinds:GetStats() or {}
    local poolStats = self.SecureFactory and self.SecureFactory:GetPoolStats() or {}
    local visualStats = self.Visuals and self.Visuals.GetStats and self.Visuals:GetStats() or {}
    return {
        enabled = db and db.enabled == true,
        version = self.VERSION,
        activeRecipe = db and db.activeRecipe or nil,
        nativeMode = db and (db.nativeMode == true or (db.appearance and db.appearance.nativeMode == true)) or false,
        buttonSkin = db and db.appearance and db.appearance.skin or nil,
        runtimeDeferredInCombat = self.runtimeDeferredInCombat == true or (db and db.runtime and db.runtime.deferredInCombat == true) or false,
        runtimeDeferredWorld = self.runtimeDeferredWorld == true or (db and db.runtime and db.runtime.deferredWorld == true) or false,
        runtimeDeferredReason = self.runtimeDeferredReason or (db and db.runtime and db.runtime.deferredReason) or nil,
        runtimeDeferredMode = self.runtimeDeferredMode or (db and db.runtime and db.runtime.deferredMode) or nil,
        runtimeDeferredOperation = self.runtimeDeferredOperation or (db and db.runtime and db.runtime.deferredOperation) or nil,
        activeBars = barStats.activeBars or 0,
        visibleBars = barStats.visibleBars or 0,
        buttonCount = barStats.buttonCount or 0,
        directActionButtonCount = barStats.directActionButtonCount or 0,
        directActionListRebuilds = barStats.directActionListRebuilds or 0,
        directActionListFallbacks = barStats.directActionListFallbacks or 0,
        cooldownPath = barStats.cooldownPath or "native-core",
        broadcaster = barStats.broadcaster or barStats.broadcasterMode or "unknown",
        broadcasterMode = barStats.broadcasterMode or barStats.broadcaster or "unknown",
        broadcasterOff = barStats.broadcasterOff or 0,
        broadcasterOn = barStats.broadcasterOn or 0,
        broadcasterRestores = barStats.broadcasterRestores or 0,
        broadcasterFallbacks = barStats.broadcasterFallbacks or 0,
        broadcasterActual = barStats.broadcasterActual or "unknown",
        broadcasterRegistered = barStats.broadcasterRegistered or 0,
        broadcasterButtonRegistered = barStats.broadcasterButtonRegistered or 0,
        broadcasterActionRegistered = barStats.broadcasterActionRegistered or 0,
        broadcasterReregisters = barStats.broadcasterReregisters or 0,
        broadcasterMismatch = barStats.broadcasterMismatch or 0,
        broadcasterCallbacksSuppressed = barStats.broadcasterCallbacksSuppressed == true,
        activeBindings = keyStats.active or 0,
        bindingSuppressed = keyStats.suppressed == true,
        bindingSuppressReason = keyStats.suppressReason,
        queuedSecureUpdates = self.Drivers and self.Drivers:QueueSize() or 0,
        driverFlushExecuted = self.Drivers and self.Drivers.flushExecuted or 0,
        driverFlushErrors = self.Drivers and self.Drivers.flushErrors or 0,
        refreshQueue = barStats.refreshQueue or 0,
        mouseoverFades = barStats.mouseoverFades or 0,
        pendingStructuralBars = barStats.pendingStructuralBars or 0,
        specialGroupingMode = barStats.specialGroupingMode or "independent",
        specialGroupActiveMembers = barStats.specialGroupActiveMembers or 0,
        specialGroupLayouts = barStats.specialGroupLayouts or 0,
        specialGroupAnchorFallbacks = barStats.specialGroupAnchorFallbacks or 0,
        nativeFrames = barStats.nativeFrames or 0,
        externalFrames = barStats.externalFrames or 0,
        strippedButtons = poolStats.strippedButtons or 0,
        detachedActionButtons = poolStats.detachedActionButtons or 0,
        events = barStats.events or 0,
        hotEventBackend = barStats.hotEventBackend,
        buttonBackend = poolStats.buttonBackend or (self.SecureFactory and self.SecureFactory.buttonBackend) or nil,
        nativeSuppressionMode = barStats.nativeSuppressionMode,
        nativeSuppressionDegraded = barStats.nativeSuppressionDegraded == true,
        nativeDisposedButtons = barStats.nativeDisposedButtons or 0,
        nativeDisposalFailures = barStats.nativeDisposalFailures or 0,
        specialNativeSuppressionMode = barStats.specialNativeSuppressionMode or "unknown",
        specialNativeSuppressionChanged = barStats.specialNativeSuppressionChanged == true,
        specialNativeSuppressionFailures = barStats.specialNativeSuppressionFailures or 0,
        reloadRequired = db and db.runtime and db.runtime.reloadRequired == true or barStats.reloadRequired == true,
        reloadRequiredReason = db and db.runtime and db.runtime.reloadRequiredReason or barStats.reloadRequiredReason,
        takeoverMode = db and db.runtime and db.runtime.takeoverMode or "strong",
        specialButtonMode = db and db.runtime and db.runtime.specialButtonMode
            or self.SPECIAL_BUTTON_MODE or "native-reuse",
        nativeSpecialButtons = poolStats.nativeSpecialButtons or 0,
        cooldownDesaturationMode = "safe-cooldown-state",
        secretSafeCooldown = true,
        pools = poolStats,
        visualStats = visualStats,
        visualImplementationType = visualStats.visualImplementationType or (self.Visuals and self.Visuals.implementationType) or nil,
        visualMode = visualStats.visualMode or "enhanced",
        visualExtraHidden = visualStats.visualExtraHidden or 0,
        visualModeSwitches = visualStats.visualModeSwitches or 0,
        skinWrites = visualStats.skinWrites or 0,
        gui2ButtonObjects = visualStats.gui2ButtonObjects or 0,
        procGlowBackend = visualStats.procGlowBackend,
        runtime = barStats.runtime == true,
        blocked = self.runtimeBlocked == true,
        blockedReason = self.runtimeBlockedReason,
        degraded = db and db.runtime and db.runtime.degraded or nil,
        lastRefreshReason = barStats.lastRefreshReason,
        fullRefreshCount = barStats.fullRefreshCount or 0,
        lastFullRefreshReason = barStats.lastFullRefreshReason,
        structuralBatchCount = barStats.structuralBatchCount or 0,
        structuralBarChangeCount =
            barStats.structuralBarChangeCount or 0,
        usablePayloadFallbacks = barStats.usablePayloadFallbacks or 0,
        slotGlobalFallbacks = barStats.slotGlobalFallbacks or 0,
        slotIdentityNarrowHits = barStats.slotIdentityNarrowHits or 0,
        slotIdentityFallbacks = barStats.slotIdentityFallbacks or 0,
        slotIdentityShadowComparisons = barStats.slotIdentityShadowComparisons or 0,
        slotIdentityShadowMismatches = barStats.slotIdentityShadowMismatches or 0,
        slotIdentityNarrowDisabled = barStats.slotIdentityNarrowDisabled == true,
        assistedCombatTickerActive = barStats.assistedCombatTickerActive == true,
        assistedCombatTickerInterval = barStats.assistedCombatTickerInterval,
        assistedCombatTickerStarts = barStats.assistedCombatTickerStarts or 0,
        assistedCombatTickerStops = barStats.assistedCombatTickerStops or 0,
        assistedCombatTickerTicks = barStats.assistedCombatTickerTicks or 0,
        assistedCombatNextSpellPolls = barStats.assistedCombatNextSpellPolls or 0,
        assistedCombatNextSpellChanges = barStats.assistedCombatNextSpellChanges or 0,
        assistedCombatNextSpellFailures = barStats.assistedCombatNextSpellFailures or 0,
        assistedCombatForceUpdates = barStats.assistedCombatForceUpdates or 0,
        assistedCombatRefreshQueues = barStats.assistedCombatRefreshQueues or 0,
        assistedCombatVisibleSlotChecks = barStats.assistedCombatVisibleSlotChecks or 0,
        rangeMapReconciles = barStats.rangeMapReconciles or 0,
        procIndexMode = barStats.procIndexMode or "shadow",
        actionIdentityGeneration = barStats.actionIdentityGeneration or 0,
        procIndexCompleteGeneration = barStats.procIndexCompleteGeneration or 0,
        procIndexShadowComparisons = barStats.procIndexShadowComparisons or 0,
        procIndexMismatches = barStats.procIndexMismatches or 0,
        procIndexRebuilds = barStats.procIndexRebuilds or 0,
        procIndexFallbacks = barStats.procIndexFallbacks or 0,
        procIndexIndexedShows = barStats.procIndexIndexedShows or 0,
        procIndexLegalEmptyShows = barStats.procIndexLegalEmptyShows or 0,
    }
end
