-- Text defaults are shared by newly normalized resources and the built-in profile.
local HIDDEN_RESOURCE_TEXT = {
    mana = true, runes = true, arcaneCharges = true, fireBlastCharges = true,
    icicles = true, tipOfTheSpear = true, vengeanceSoulFragments = true,
}
for id, definition in pairs(DEFINITIONS) do
    if HIDDEN_RESOURCE_TEXT[id] then definition.defaultValueText = false end
    local kind = definition.provider and definition.provider.kind
    definition.defaultValueFormat = (id == "mana" and "percent")
        or ((id == "stagger" or id == "ignorePain") and "percentSign")
        or (kind == "aura-duration" and "duration") or "value"
end

